// Map various Likert-style option labels to a 5..1 scale
const OPTION_POINTS: Record<string, number> = {
  'strongly agree': 5,
  'agree': 4,
  'neutral': 3,
  'disagree': 2,
  'strongly disagree': 1,
  'yes, always': 5,
  'most of the time': 4,
  'sometimes': 3,
  'rarely': 2,
  'never': 1,
  'always': 5,
  'often': 4,
  'very often': 5,
  'very much': 5,
  'mostly yes': 4,
  'yes': 5,
  'mostly no': 2,
  'no': 1,
  'strongly prefer': 5,
  'prefer': 4,
  'dislike': 2,
  'strongly dislike': 1,
};

export const scorePersonalityAnswer = (question: Question, optionIndex: number): number => {
  const label = (question.options[optionIndex] || '').toLowerCase().trim();
  if (label in OPTION_POINTS) return OPTION_POINTS[label];
  // Fallback: map by position for any unmatched sets (left-most high, right-most low)
  const count = question.options.length;
  const positionFromLeft = optionIndex; // 0-based
  const ratio = (count - positionFromLeft) / count; // 0..1
  return Math.max(1, Math.min(5, Math.round(ratio * 5)));
};

export const aggregatePersonalityScore = (answers: number[], qs: Question[] = personalityQuestions) => {
  let total = 0;
  let max = 0;
  for (let i = 0; i < answers.length; i++) {
    const q = qs[i];
    if (!q) continue;
    const pts = scorePersonalityAnswer(q, answers[i]);
    total += pts;
    max += 5;
  }
  const percent = max > 0 ? Math.round((total / max) * 100) : 0;
  return { total, max, percent };
};

export const getPersonalityLevel = (percent: number): string => {
  if (percent >= 85) return 'Very High';
  if (percent >= 70) return 'High';
  if (percent >= 55) return 'Moderate';
  if (percent >= 40) return 'Low';
  return 'Very Low';
};


